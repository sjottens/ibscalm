/**
 * Generates every IBScalm logo asset from one source of truth (logo direction A, "Kalme golf").
 *
 *   node scripts/generate-logo.mjs
 *
 * Output:
 *   components/ui/logo-data.ts            vector paths used by the <Logo/> component (inline SVG)
 *   public/logos/ibscalm-icon.svg         app icon (rounded)
 *   public/logos/ibscalm-logo.svg         horizontal logo for light backgrounds
 *   public/logos/ibscalm-logo-dark.svg    horizontal logo for dark backgrounds
 *   public/logos/*.png                    rendered sizes (logo, app icons, apple touch icon)
 *   public/ibscalm-favicon-{16,32,64}.png and public/favicon.ico
 *
 * The wordmark is converted from Nunito (SIL Open Font License) to paths, so the logo never
 * depends on a font being loaded.
 */
import { readFileSync, writeFileSync, rmSync, existsSync } from "node:fs";
import { execFileSync } from "node:child_process";
import opentype from "opentype.js";
import { chromium } from "@playwright/test";

const TEAL = "#23485a";
const CORAL = "#ef8a6c";
const CREAM = "#fff7f0";

// The calm wave: starts restless, ends as a straight line.
const WAVE = "M8.5 24c2.4-7.2 6.6-7.2 9 0 1.8 5.4 4.8 5.4 6.6 0 1.3-3.6 3.5-3.6 4.8 0 .9 2.2 3 2.2 4.6 0H39.5";
const waveEl = `<path d="${WAVE}" fill="none" stroke="${CORAL}" stroke-width="3.6" stroke-linecap="round" stroke-linejoin="round"/>`;
const iconInner = (rx) => `<rect width="48" height="48" rx="${rx}" fill="${TEAL}"/>${waveEl}`;

// ── Wordmark → paths ──────────────────────────────────────────────────────
const fontDir = "node_modules/@fontsource/nunito/files";
const load = (w) => opentype.parse(readFileSync(`${fontDir}/nunito-latin-${w}-normal.woff`).buffer);
const bold = load(800);
const semi = load(600);

const FONT_SIZE = 31.2; // same proportion as the approved concept (word height vs. icon)
const GAP = 12; // space between icon and word, in icon units (icon = 48)
const startX = 48 + GAP;

/** Lays out glyphs one by one (with kerning) — avoids opentype.js's partial GSUB support. */
function textPath(font, text, x, size) {
  const scale = size / font.unitsPerEm;
  const path = new opentype.Path();
  let prev = null;
  for (const ch of text) {
    const g = font.charToGlyph(ch);
    if (prev) x += font.getKerningValue(prev, g) * scale;
    path.extend(g.getPath(x, 0, size));
    x += g.advanceWidth * scale;
    prev = g;
  }
  return { path, end: x };
}
const ibs = textPath(bold, "ibs", startX, FONT_SIZE);
const ibsPath = ibs.path;
const calmPath = textPath(semi, "calm", ibs.end, FONT_SIZE).path;

// Centre the word vertically on the icon (no descenders in "ibscalm").
const b1 = ibsPath.getBoundingBox();
const b2 = calmPath.getBoundingBox();
const top = Math.min(b1.y1, b2.y1);
const bottom = Math.max(b1.y2, b2.y2);
const dy = 24 - (top + bottom) / 2;
const shift = (p) => {
  for (const c of p.commands) {
    for (const k of ["y", "y1", "y2"]) if (k in c) c[k] += dy;
  }
  return p;
};
shift(ibsPath);
shift(calmPath);
const right = Math.max(b1.x2, b2.x2);
const WIDTH = Math.ceil(right + 2);
const ibsD = ibsPath.toPathData(2);
const calmD = calmPath.toPathData(2);

const logoSvg = (ibsColor) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${WIDTH} 48" width="${WIDTH * 8}" height="384">` +
  `<title>IBScalm</title>${iconInner(13)}<path d="${ibsD}" fill="${ibsColor}"/><path d="${calmD}" fill="${CORAL}"/></svg>\n`;
const iconSvg = (rx = 13) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 48 48" width="512" height="512"><title>IBScalm</title>${iconInner(rx)}</svg>\n`;

// ── Write vector files ────────────────────────────────────────────────────
writeFileSync("public/logos/ibscalm-logo.svg", logoSvg(TEAL));
writeFileSync("public/logos/ibscalm-logo-dark.svg", logoSvg(CREAM));
writeFileSync("public/logos/ibscalm-icon.svg", iconSvg(13));
for (const old of ["public/logos/ibscalm-golf.svg"]) if (existsSync(old)) rmSync(old);

writeFileSync(
  "components/ui/logo-data.ts",
  `// Generated by scripts/generate-logo.mjs — do not edit by hand.
export const LOGO_WIDTH = ${WIDTH};
export const LOGO_HEIGHT = 48;
export const LOGO_COLORS = { teal: "${TEAL}", coral: "${CORAL}", cream: "${CREAM}" } as const;
export const WAVE_PATH = "${WAVE}";
export const IBS_PATH = "${ibsD}";
export const CALM_PATH = "${calmD}";
`,
);

// ── Render PNGs ───────────────────────────────────────────────────────────
const browser = await chromium.launch();
const page = await browser.newPage();
async function png(svg, w, h, file, { opaque = false } = {}) {
  await page.setViewportSize({ width: w, height: h });
  const sized = svg.replace(/width="\d+" height="\d+"/, `width="${w}" height="${h}"`);
  await page.setContent(
    `<html><body style="margin:0;background:${opaque ? TEAL : "transparent"}">${sized}</body></html>`,
  );
  await page.screenshot({ path: file, omitBackground: !opaque, clip: { x: 0, y: 0, width: w, height: h } });
}

const logoRatio = WIDTH / 48;
await png(logoSvg(TEAL), Math.round(256 * logoRatio), 256, "public/logos/ibscalm-logo-horizontaal.png");
await png(logoSvg(TEAL), Math.round(512 * logoRatio), 512, "public/logos/ibscalm-logo-horizontaal@2x.png");
await png(logoSvg(CREAM), Math.round(512 * logoRatio), 512, "public/logos/ibscalm-logo-horizontaal-dark@2x.png");

// Rounded icons (transparent corners) for browsers, Android "any" and in-app use.
await png(iconSvg(13), 256, 256, "public/logos/ibscalm-icon-rounded-256.png");
await png(iconSvg(13), 512, 512, "public/logos/ibscalm-icon-rounded-512.png");
await png(iconSvg(13), 192, 192, "public/logos/ibscalm-android-icon-192.png");
// Full-bleed, opaque icons: Android "maskable" and iOS round the corners themselves.
await png(iconSvg(0), 512, 512, "public/logos/ibscalm-app-icon-512.png", { opaque: true });
await png(iconSvg(0), 1024, 1024, "public/logos/ibscalm-app-icon-1024.png", { opaque: true });
await png(iconSvg(0), 180, 180, "public/logos/ibscalm-apple-touch-icon-180.png", { opaque: true });
// Favicons.
for (const s of [16, 32, 64]) await png(iconSvg(s <= 16 ? 10 : 12), s, s, `public/ibscalm-favicon-${s}.png`);
await browser.close();

execFileSync("node", ["scripts/make-favicon.mjs"], { stdio: "inherit" });
console.log(`Logo generated: viewBox ${WIDTH}×48`);
